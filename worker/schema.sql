-- NEERAJ Cloud schema (Cloudflare D1 - SQLite).
--
-- Apply with:
--   npx wrangler d1 execute neeraj-cloud --remote --file=worker/schema.sql

CREATE TABLE IF NOT EXISTS messages (
    id          TEXT PRIMARY KEY,       -- generated by the client, so re-sending is safe
    session_id  TEXT NOT NULL DEFAULT 'web',
    role        TEXT NOT NULL,
    content     TEXT NOT NULL,
    ts          INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_ts ON messages(ts DESC);
CREATE INDEX IF NOT EXISTS idx_messages_session ON messages(session_id, ts DESC);

-- Voice notes captured on the phone while NEERAJ was unreachable.
CREATE TABLE IF NOT EXISTS notes (
    id          TEXT PRIMARY KEY,
    text        TEXT NOT NULL,
    lang        TEXT NOT NULL DEFAULT '',
    captured_at INTEGER NOT NULL,
    synced      INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_notes_pending ON notes(synced, captured_at);

-- Reminders live here so the Cron Trigger can fire them with your PC off.
CREATE TABLE IF NOT EXISTS reminders (
    id          TEXT PRIMARY KEY,
    text        TEXT NOT NULL,
    due_at      INTEGER NOT NULL,
    created_at  INTEGER NOT NULL,
    status      TEXT NOT NULL DEFAULT 'pending',   -- pending | done | cancelled
    notified_at INTEGER,
    source      TEXT NOT NULL DEFAULT 'neeraj'
);
CREATE INDEX IF NOT EXISTS idx_reminders_due ON reminders(status, due_at);
